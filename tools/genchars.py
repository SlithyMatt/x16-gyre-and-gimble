#!/usr/bin/env python3
"""Compile text glyphs (see assets/stars.txt) into 1bpp charset data.

Each glyph is cut into 8x8 characters, left to right then top to bottom,
and all of them are emitted in order as NAME_chars (8 bytes per character).
NAME_GLYPH is the index of each glyph's first character.

Usage: genchars.py SHEET.txt NAME OUT.inc
"""
import sys


def main():
    path, name, out = sys.argv[1:4]
    glyphs, cur = {}, None
    for raw in open(path):
        line = raw.split("#", 1)[0].rstrip()
        if not line:
            continue
        toks = line.split()
        if toks[0] == "glyph":
            cur = glyphs[toks[1]] = []
        elif cur is not None:
            if any(ch not in ".@" for ch in line):
                sys.exit(f"{path}: bad row {line!r}")
            cur.append(line)
    for gname, rows in glyphs.items():
        w, h = len(rows[0]), len(rows)
        if w % 8 or h % 8 or any(len(r) != w for r in rows):
            sys.exit(f"{path}: glyph {gname} is not a multiple of 8x8")

    with open(out, "w") as f:
        f.write(f"; generated by tools/genchars.py from {path} — do not edit\n")
        chars = []
        for gname, rows in glyphs.items():
            f.write(f"{name.upper()}_{gname.upper()} = {len(chars)}\n")
            for ty in range(0, len(rows), 8):
                for tx in range(0, len(rows[0]), 8):
                    chars.append([int(r[tx:tx + 8].replace(".", "0").replace("@", "1"), 2)
                                  for r in rows[ty:ty + 8]])
        f.write(f"{name.upper()}_CHARS = {len(chars)}\n{name}_chars:\n")
        for c in chars:
            f.write("    .byte " + ", ".join(f"${v:02x}" for v in c) + "\n")


if __name__ == "__main__":
    main()

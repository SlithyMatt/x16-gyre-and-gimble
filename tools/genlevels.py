#!/usr/bin/env python3
"""Generate the levels.

Levels are numbered here as they were first generated, after three
hand-made levels that have since gone: generation number n is written as
level n - SHIFT. So `genlevels.py 4 103` writes levels 1-100, and the
difficulty ramp and each level's seed stay as they were.

Each level is built around a path from the entry to the burrow: down
through every ring, wandering along each ring's arc on the way. Decoy
tunnels (dead ends and false turnings) go around it, gimbals link rings,
and then the rings are scrambled to a start whose par is exactly the
target: a breadth-first search out from every solved state gives each
state's distance, so the start is picked from those at the right one.

Difficulty grows with the level number: par, the arcs' lengths and the
decoys all increase, and gimbals arrive in stages (one same-way gimbal,
then an opposite one, then pairs and chains). The first level of each
ten is a little easier, a breather. Themes change every ten levels.

Writes levels/levelNNN.txt (overwriting). Deterministic for a given seed.

Usage: genlevels.py FIRST LAST [SEED]   (generation numbers: normally 4 103)
"""
import os
import random
import sys
import tempfile
from collections import deque

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from level import CELLS, CW, IN, OUT, RINGS, T, THEMES, Level  # noqa: E402

ROOT = __file__.rsplit("/", 2)[0]
NSTATES = CELLS ** RINGS
FIRST, LAST = 4, 100    # the difficulty ramp runs over these (generation numbers;
                        # past LAST it holds at its hardest)
SHIFT = 3               # generation number n is level n - SHIFT
MAX_SOLVED = 0.02       # reject boards where decoys make too many states solve


def schedule(n):
    """Difficulty knobs for level n: (par, max arc, decoys, decoy length, links)."""
    t = min(1.0, (n - FIRST) / (LAST - FIRST))
    par = 4 + round(10 * t)
    if n % 10 == 1:
        par -= 2                    # breather at the start of each ten
    arc = 1 + round(3 * t)
    decoys = 2 + round(5 * t)
    length = 1 + round(2 * t)
    if n < 8:
        links = 0
    elif n < 24:
        links = 1
    elif n < 40:
        links = 1 + (n % 3 == 0)
    elif n < 70:
        links = 1 + (n % 2 == 0)
    else:
        links = 2 + (n % 3 == 0)
    return max(3, par), arc, decoys, length, links


def gimbal_kind(n, rng):
    """Sign of a gimbal: same-way first, then opposite, then either."""
    if n < 16:
        return "+"
    if n < 24:
        return "-"
    return rng.choice("+-")


def make_board(rng, arc, decoys, length):
    cells = [[0] * CELLS for _ in range(RINGS)]
    used = [set() for _ in range(RINGS)]
    p = 0
    for r in range(RINGS - 1, -1, -1):
        cells[r][p] |= T
        if r == RINGS - 1:
            cells[r][p] |= OUT              # the entry
        used[r].add(p)
        steps, d = rng.randint(arc // 2, arc), rng.choice((1, -1))
        for _ in range(steps):
            q = (p + d) % CELLS
            cells[r][q] |= T
            cells[r][p if d > 0 else q] |= CW
            used[r].add(q)
            p = q
        cells[r][p] |= IN                   # down to the next ring, or the burrow
        if r > 0:
            cells[r - 1][p] |= T | OUT
    for _ in range(decoys):
        for _attempt in range(20):
            r = rng.randrange(RINGS)
            n = rng.randint(1, length)
            q = rng.randrange(CELLS)
            span = [(q + i) % CELLS for i in range(n)]
            if any(s in used[r] for s in span):
                continue
            for i, s in enumerate(span):
                cells[r][s] |= T
                if i < n - 1:
                    cells[r][s] |= CW
                used[r].add(s)
            # openings at the ends; never a second entry or burrow door
            ends = {span[0], span[-1]}
            for s in ends:
                choices = []
                if r > 0:
                    choices.append(IN)
                if r < RINGS - 1:
                    choices.append(OUT)
                cells[r][s] |= rng.choice(choices)
            break
    return cells


def cell_token(v):
    if not v & T:
        return "."
    s = ("o" if v & OUT else "") + ("i" if v & IN else "") + ("c" if v & CW else "")
    return s or "-"


def write(path, n, cells, links, start, theme, note):
    with open(path, "w") as f:
        f.write(f"# Gyre & Gimble — level {n - SHIFT}\n")
        f.write(f"# Generated by tools/genlevels.py ({note}); format: see tools/level.py.\n\n")
        for r in range(RINGS - 1, -1, -1):
            f.write(f"ring{r}: " + " ".join(cell_token(v).ljust(3) for v in cells[r]).rstrip() + "\n")
        f.write("\n")
        for a, b, s in links:
            f.write(f"gimbal: {a} > {b} {s}\n")
        if links:
            f.write("\n")
        f.write(f"start: {' '.join(str(o) for o in reversed(start))}\n\ntheme: {theme}\n")


def distances(lv):
    """Moves from every state to the nearest solved state (None: board rejected)."""
    states = [(a, b, c, d) for a in range(CELLS) for b in range(CELLS)
              for c in range(CELLS) for d in range(CELLS)]
    solved = [s for s in states if lv.solved(s)]
    if not solved or len(solved) > MAX_SOLVED * NSTATES:
        return None
    dist = {s: 0 for s in solved}
    q = deque(solved)
    while q:
        s = q.popleft()
        for r in range(RINGS):
            for d in (1, -1):
                n = lv.turn(s, r, -d)       # undo a move
                if n not in dist:
                    dist[n] = dist[s] + 1
                    q.append(n)
    return dist


def generate(n, rng):
    par, arc, decoys, length, nlinks = schedule(n)
    theme = THEMES[((n - 1) // 10) % len(THEMES)]
    tmp = os.path.join(tempfile.gettempdir(), f"genlevel{os.getpid()}.txt")
    for _attempt in range(200):
        cells = make_board(rng, arc, decoys, length)
        pairs = rng.sample([(k, k - 1) for k in range(1, RINGS)], nlinks)
        links = []
        for k, j in pairs:
            a, b = (k, j) if rng.random() < 0.5 else (j, k)     # either may drive
            links.append((a, b, gimbal_kind(n, rng)))
        write(tmp, n, cells, links, [1] * RINGS, theme, "")
        lv = Level(tmp)
        dist = distances(lv)
        if dist is None:
            continue
        want = [s for s, v in dist.items() if v == par]
        if not want:
            continue
        start = rng.choice(want)
        os.remove(tmp)
        return cells, links, list(start), theme, par
    sys.exit(f"level {n}: no board found")


def main():
    first, last = int(sys.argv[1]), int(sys.argv[2])
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 1871
    for n in range(first, last + 1):
        rng = random.Random(seed * 1000 + n)
        cells, links, start, theme, par = generate(n, rng)
        path = os.path.join(ROOT, "levels", f"level{n - SHIFT:03d}.txt")
        write(path, n, cells, links, start, theme, f"seed {seed}, par {par}")
        print(f"{path}: par {par}, {len(links)} gimbal(s), {theme}")


if __name__ == "__main__":
    main()

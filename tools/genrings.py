#!/usr/bin/env python3
"""Generate the ring-board bitmap (320x240, 8bpp, headerless) for VERA layer 0.

Every pixel's color index names a fixed screen region; the game colors the
board at runtime by rewriting palette entries (see DESIGN.md).

It also writes the screen coordinates the tove walks through: every cell
center, arc gate and radial gate, plus the entry and the burrow.

Usage: genrings.py OUT_BITMAP OUT_REGIONS_INC OUT_WAYPOINTS_INC
"""
import math
import sys

W, H = 320, 240
CX, CY = 160, 120
RINGS, CELLS = 4, 12
STEP = 360 / CELLS

# Everything stays inside the CRT title-safe area (10% margins: x 32-287,
# y 24-215). The board's outer edge is at radius 88, leaving 8x4-character
# corners for the HUD.
BURROW_R = 12       # burrow radius
RING_IN0 = 16       # inner radius of ring 0
RING_PITCH = 18     # distance between rings' inner radii
RING_W = 14         # ring band width (the gap is RING_PITCH - RING_W)
GAP_W = RING_PITCH - RING_W
RADIAL_HALF = 4.0   # max half-width of a radial gate, in pixels
RADIAL_ANG = 9.0    # max half-width of a radial gate, in degrees (inner gaps)
ARC_HALF = 1.5      # half-width of an arc gate (cell separator), in pixels
TOOTH_LEN = 8.0     # gimbal gear-tooth pitch along the gap, in pixels

# Palette region indices (0-15 are left to the text layer)
BG = 0
BODY = 16           # + r*12 + p
RGATE = 64          # + r*12 + p : gate on the inner side of ring r
AGATE = 112         # + r*12 + p : gate between positions p and p+1
ENTRY = 160
BURROW = 161
WALL = 162
TEETH = 163         # + k - 1 : gear teeth in the gap between rings k-1 and k


def ring_in(r):
    return RING_IN0 + r * RING_PITCH


def angdiff(a, b):
    d = (a - b) % 360
    return min(d, 360 - d)


def classify(x, y):
    dx, dy = x + 0.5 - CX, y + 0.5 - CY
    d = math.hypot(dx, dy)
    a = math.degrees(math.atan2(dx, -dy)) % 360   # 0 = up, clockwise
    p = round(a / STEP) % CELLS                   # nearest cell center

    if d < BURROW_R:
        return BURROW
    for r in range(RINGS + 1):
        lo = ring_in(r) - GAP_W
        if lo <= d < ring_in(r):                  # gap on the inner side of ring r
            off = angdiff(a, p * STEP)
            if d * math.radians(off) < RADIAL_HALF and off < RADIAL_ANG:
                if r < RINGS:
                    return RGATE + r * CELLS + p
                if p == 0:
                    return ENTRY
            if 0 < r < RINGS:
                n = round(2 * math.pi * (lo + GAP_W / 2) / TOOTH_LEN)
                if int(a / 360 * n * 2) % 2 == 0:
                    return TEETH + r - 1
            return WALL
        if r < RINGS and ring_in(r) <= d < ring_in(r) + RING_W:
            k = round((a - STEP / 2) / STEP) % CELLS  # nearest boundary k|k+1
            if d * math.radians(angdiff(a, k * STEP + STEP / 2)) < ARC_HALF:
                return AGATE + r * CELLS + k
            return BODY + r * CELLS + p
    return BG


def point(radius, angle):
    a = math.radians(angle)
    return round(CX + radius * math.sin(a)), round(CY - radius * math.cos(a))


def waypoints(f):
    """Byte tables of x/y per cell index r*12+p (the board fits in x < 256)."""
    tables = {"cx": [], "cy": [], "ax": [], "ay": [], "rx": [], "ry": []}
    for r in range(RINGS):
        mid = ring_in(r) + RING_W / 2
        gap = ring_in(r) - GAP_W / 2
        for p in range(CELLS):
            for key, (x, y) in (("c", point(mid, p * STEP)),
                                ("a", point(mid, p * STEP + STEP / 2)),
                                ("r", point(gap, p * STEP))):
                tables[key + "x"].append(x)
                tables[key + "y"].append(y)
    ex, ey = point(ring_in(RINGS) - GAP_W / 2, 0)
    f.write("; generated by tools/genrings.py — do not edit\n")
    f.write(f"ENTRY_X = {ex}\nENTRY_Y = {ey}\nBURROW_X = {CX}\nBURROW_Y = {CY}\n")
    names = {"c": "cell center", "a": "arc gate to the clockwise neighbor",
             "r": "radial gate on the inner side"}
    for key, vals in tables.items():
        assert all(0 <= v < 256 for v in vals)
        f.write(f"wp_{key}:  ; {names[key[0]]}, {key[1]}\n")
        for k in range(0, len(vals), CELLS):
            f.write("    .byte " + ", ".join(map(str, vals[k:k + CELLS])) + "\n")


def main():
    out_bin, out_inc, out_wp = sys.argv[1], sys.argv[2], sys.argv[3]
    pixels = bytes(classify(x, y) for y in range(H) for x in range(W))
    with open(out_bin, "wb") as f:
        f.write(pixels)
    with open(out_inc, "w") as f:
        f.write("; generated by tools/genrings.py — do not edit\n")
        for name in ("BODY", "RGATE", "AGATE", "ENTRY", "BURROW", "WALL", "TEETH"):
            f.write(f"REG_{name} = {globals()[name]}\n")
    with open(out_wp, "w") as f:
        waypoints(f)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Compile a text sprite sheet (see assets/tove.txt) into ca65 data.

Each frame stacks layers (later layers draw over earlier ones; "." is
transparent). Output: NAME_pal (15 palette entries for indices 1-15, as
VERA GB/R byte pairs) and NAME_frames (16x16 4bpp, 128 bytes per frame).

Usage: gensprites.py SHEET.txt NAME OUT.inc
"""
import sys

SIZE = 16


def main():
    path, name, out = sys.argv[1:4]
    colors, layers, frames = {".": (0, None)}, {}, []
    cur = None
    for raw in open(path):
        line = raw.split("#", 1)[0].rstrip()
        if not line:
            continue
        toks = line.split()
        if toks[0] == "color":
            colors[toks[1]] = (len(colors), tuple(int(v) for v in toks[2:5]))
            cur = None
        elif toks[0] == "layer":
            cur = layers[toks[1]] = []
        elif toks[0] == "frame":
            frames.append(toks[1:])
            cur = None
        elif cur is not None:
            if len(line) != SIZE or any(ch not in colors for ch in line):
                sys.exit(f"{path}: bad row {line!r}")
            cur.append(line)
    if len(colors) > 16:
        sys.exit(f"{path}: more than 15 colors")
    for lname, rows in layers.items():
        if len(rows) != SIZE:
            sys.exit(f"{path}: layer {lname} has {len(rows)} rows")

    with open(out, "w") as f:
        f.write(f"; generated by tools/gensprites.py from {path} — do not edit\n")
        f.write(f"{name.upper()}_FRAMES = {len(frames)}\n")
        f.write(f"{name}_pal:\n")
        for ch, (idx, rgb) in sorted(colors.items(), key=lambda kv: kv[1][0]):
            if rgb:
                r, g, b = rgb
                f.write(f"    .byte ${g << 4 | b:02x}, ${r:02x}  ; {idx} {ch}\n")
        f.write(f"{name}_frames:\n")
        for n, stack in enumerate(frames):
            grid = [["."] * SIZE for _ in range(SIZE)]
            for lname in stack:
                for y, row in enumerate(layers[lname]):
                    for x, ch in enumerate(row):
                        if ch != ".":
                            grid[y][x] = ch
            data = []
            for row in grid:
                idx = [colors[ch][0] for ch in row]
                data += [idx[x] << 4 | idx[x + 1] for x in range(0, SIZE, 2)]
            f.write(f"    ; frame {n}: {' + '.join(stack)}\n")
            for k in range(0, len(data), 16):
                f.write("    .byte " + ", ".join(f"${v:02x}" for v in data[k:k + 16]) + "\n")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate a scripted SNES pad for the JOY_SCRIPT test build (make joytest).

Plays every level's shortest solution with the D-pad, exercising hold-to-
repeat, undo (B), restart (Select) and level advance (A / Start). Each entry
is one frame of pad 1, active-low like JOYSTICK_GET; byte 1 = 0 ends it.

Usage: joyscript.py OUT.inc LEVEL.txt...
"""
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from level import Level, keys  # noqa: E402

JOY_DELAY, JOY_RATE = 18, 8         # must match src/main.asm
B, SEL, START, UP, DOWN, LEFT, RIGHT = 0x80, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01
A = 0x8000                          # byte 1, bit 7
DPAD = {"w": UP, "s": DOWN, "a": LEFT, "d": RIGHT}

frames = []


def idle(n=1):
    frames.extend([0] * n)


def press(buttons, n=1):
    """Hold buttons for long enough to register n presses, then release."""
    held = 1 if n == 1 else 1 + JOY_DELAY + (n - 2) * JOY_RATE
    frames.extend([buttons] * held)
    idle()


def play(ks):
    """Play WASD keys; runs of the same key use hold-to-repeat."""
    i = 0
    while i < len(ks):
        j = i
        while j < len(ks) and ks[j] == ks[i]:
            j += 1
        press(DPAD[ks[i]], j - i)
        i = j


def main():
    out, paths = sys.argv[1], sys.argv[2:]
    advance = [A, START]
    idle(10)
    for n, path in enumerate(paths):
        sol = keys(Level(path).solve())
        if n == 1:                  # a wrong move, undone with B
            play("d")
            press(B)
        if n == 2:                  # some moves, thrown away with Select
            play(sol[:4])
            press(SEL)
        play(sol)
        idle(5)
        if n < len(paths) - 1:
            press(advance[n % 2])   # skips the tove's walk if it's still going
            idle(3)
            press(advance[n % 2])   # ... then advances
            idle(5)
    with open(out, "w") as f:
        f.write("; generated by tools/joyscript.py — do not edit\njoy_script:\n")
        for b in frames:
            f.write(f"    .byte ${~b & 0xff:02x}, ${(~(b >> 8) & 0xf0) | 0x0f:02x}\n")
        f.write("    .byte $ff, $00          ; end\n")
    print(f"{out}: {len(frames)} frames")


if __name__ == "__main__":
    main()

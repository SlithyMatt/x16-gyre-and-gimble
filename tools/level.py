#!/usr/bin/env python3
"""Compile a level text file into ca65 data, verifying it is solvable.

Usage:
  level.py LEVEL.txt OUT.inc        compile (fails if unsolvable)
  level.py LEVEL.txt --suggest PAR  list start offsets whose par is PAR
  level.py LEVEL.txt --keys         print a shortest solution as WASD keys

Connectivity here must match `flood` in src/main.asm.
"""
import random
import sys
from collections import deque

RINGS, CELLS = 4, 12
IN, OUT, CW, T = 0x01, 0x02, 0x04, 0x80
BITS = {"i": IN, "o": OUT, "c": CW, "-": 0}


def parse(path):
    rings, start = {}, None
    for line in open(path):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        key, _, val = line.partition(":")
        toks = val.split()
        if key.startswith("ring"):
            r = int(key[4:])
            if len(toks) != CELLS:
                sys.exit(f"{path}: {key} needs {CELLS} cells")
            row = []
            for t in toks:
                if t == ".":
                    row.append(0)
                else:
                    v = T
                    for ch in t:
                        v |= BITS[ch]
                    row.append(v)
            rings[r] = row
        elif key == "start":
            start = [int(t) % CELLS for t in toks]   # listed outer to inner
            start.reverse()
    cells = [rings[r] for r in range(RINGS)]
    for r in range(RINGS):
        for p in range(CELLS):
            if cells[r][p] & CW and not cells[r][(p + 1) % CELLS] & T:
                sys.exit(f"{path}: ring{r} cell {p} opens clockwise into stone")
    return cells, start


def solved(cells, off):
    def scr(r, p):
        return cells[r][(p - off[r]) % CELLS]

    if not scr(RINGS - 1, 0) & OUT:
        return False
    seen, todo = {(RINGS - 1, 0)}, [(RINGS - 1, 0)]
    while todo:
        r, p = todo.pop()
        c = scr(r, p)
        if r == 0 and c & IN:
            return True
        nbrs = []
        if c & CW:
            nbrs.append((r, (p + 1) % CELLS))
        if scr(r, (p - 1) % CELLS) & CW:
            nbrs.append((r, (p - 1) % CELLS))
        if r > 0 and c & IN and scr(r - 1, p) & OUT:
            nbrs.append((r - 1, p))
        if r < RINGS - 1 and c & OUT and scr(r + 1, p) & IN:
            nbrs.append((r + 1, p))
        for n in nbrs:
            if n not in seen:
                seen.add(n)
                todo.append(n)
    return False


def solve(cells, start):
    """Shortest list of (ring, dir) single-step rotations to a solved board."""
    start = tuple(start)
    prev = {start: None}
    q = deque([start])
    while q:
        s = q.popleft()
        if solved(cells, s):
            moves = []
            while prev[s]:
                s, move = prev[s]
                moves.append(move)
            return moves[::-1]
        for r in range(RINGS):
            for d in (1, -1):
                n = list(s)
                n[r] = (n[r] + d) % CELLS
                n = tuple(n)
                if n not in prev:
                    prev[n] = (s, (r, d))
                    q.append(n)
    return None


def par(cells, start):
    """Fewest single-step rotations from start to a solved board."""
    moves = solve(cells, start)
    return None if moves is None else len(moves)


def keys(moves):
    """Keystrokes (WASD) that play moves, starting with the outer ring selected."""
    out, sel = [], RINGS - 1
    for r, d in moves:
        out.append(("w" if r > sel else "s") * abs(r - sel))
        out.append("d" if d > 0 else "a")
        sel = r
    return "".join(out)


def main():
    path = sys.argv[1]
    cells, start = parse(path)
    if sys.argv[2] == "--keys":
        print(keys(solve(cells, start)))
        return
    if sys.argv[2] == "--suggest":
        want = int(sys.argv[3])
        rng = random.Random(1)
        found = 0
        while found < 5:
            s = [rng.randrange(CELLS) for _ in range(RINGS)]
            if par(cells, s) == want:
                print("start:", " ".join(map(str, reversed(s))))
                found += 1
        return

    if start is None:
        sys.exit(f"{path}: missing start:")
    p = par(cells, start)
    if p is None:
        sys.exit(f"{path}: unsolvable")
    if p == 0:
        sys.exit(f"{path}: already solved at start")
    with open(sys.argv[2], "w") as f:
        f.write(f"; generated by tools/level.py from {path} — do not edit\n")
        f.write(f"LEVEL_PAR = {p}\n")
        f.write("level_cells:\n")
        for r in range(RINGS):
            f.write("    .byte " + ", ".join(f"${c:02x}" for c in cells[r]) + f"  ; ring {r}\n")
        f.write("level_start:\n")
        f.write("    .byte " + ", ".join(map(str, start)) + "\n")
    print(f"{path}: par {p}")


if __name__ == "__main__":
    main()
